<?php
/**
 * Plugin Name: Headless bridge
 * Description: Connects this WordPress to the headless site: editable content of the site's own pages, language fields for Polylang in the REST API, signed change notifications (cache purge on publish), visitors sent to the site, and, with WooCommerce, the return from redirect payment gateways.
 * Version: 2.2.0
 *
 * Install: copy this file to wp-content/mu-plugins/ (loads automatically; `npm run wp:up`
 * mounts it) and add to wp-config.php:
 *
 *   define( 'HEADLESS_SITE_URL', 'https://www.client.gr' );
 *   define( 'HEADLESS_WEBHOOK_SECRET', '…same value as WORDPRESS_WEBHOOK_SECRET…' );
 *
 * Optional: define( 'HEADLESS_WEBHOOK_URL', '…' ) when WordPress reaches the site at another
 * address than visitors do (Docker, private network). Default: HEADLESS_SITE_URL/api/wordpress/webhook.
 *
 * headless-fields.json next to this file (generated by `npm run wp:fields`) describes the
 * site's own pages and their fields.
 */

defined( 'ABSPATH' ) || exit;

// COMMERCE_SITE_URL: the name used by version 1 of this plugin.
if ( ! defined( 'HEADLESS_SITE_URL' ) && defined( 'COMMERCE_SITE_URL' ) ) {
	define( 'HEADLESS_SITE_URL', COMMERCE_SITE_URL );
}
if ( ! defined( 'HEADLESS_SITE_URL' ) ) {
	return;
}

function headless_site_url( $path = '', array $args = array() ) {
	return add_query_arg( $args, untrailingslashit( HEADLESS_SITE_URL ) . $path );
}

// Redirects to the site (gateways, previews) go through wp_safe_redirect(), which only allows known hosts.
add_filter(
	'allowed_redirect_hosts',
	function ( $hosts ) {
		$hosts[] = wp_parse_url( HEADLESS_SITE_URL, PHP_URL_HOST );
		return $hosts;
	}
);

/* ---------------------------------------------------------------- the site's own pages */

function headless_site_config() {
	static $config = null;
	if ( null === $config ) {
		$file   = __DIR__ . '/headless-fields.json';
		$config = is_readable( $file ) ? (array) json_decode( (string) file_get_contents( $file ), true ) : array();
		$config += array( 'defaultLang' => 'en', 'shopPath' => 'shop', 'pages' => array() );
	}
	return $config;
}

function headless_page_ids( $key ) {
	return get_posts(
		array(
			'post_type'        => 'page',
			'post_status'      => 'any',
			'numberposts'      => -1,
			'fields'           => 'ids',
			'meta_key'         => 'headless_page_key', // phpcs:ignore WordPress.DB.SlowDBQuery
			'meta_value'       => $key, // phpcs:ignore WordPress.DB.SlowDBQuery
			'lang'             => '', // every language (Polylang)
			'suppress_filters' => false,
		)
	);
}

function headless_post_lang( $id ) {
	$lang = function_exists( 'pll_get_post_language' ) ? pll_get_post_language( $id, 'slug' ) : '';
	return $lang ? $lang : headless_site_config()['defaultLang'];
}

// Field groups for the site's pages, attached to the WordPress page of each page key.
add_action(
	'acf/init',
	function () {
		foreach ( headless_site_config()['pages'] as $key => $page ) {
			$ids = headless_page_ids( $key );
			if ( ! $ids || empty( $page['fields'] ) ) {
				continue;
			}
			acf_add_local_field_group(
				array(
					'key'            => "group_headless_{$key}",
					'title'          => 'Page content',
					'fields'         => $page['fields'],
					'location'       => array_map( fn( $id ) => array( array( 'param' => 'page', 'operator' => '==', 'value' => (string) $id ) ), $ids ),
					'position'       => 'acf_after_title',
					'style'          => 'seamless',
					'hide_on_screen' => array( 'the_content', 'excerpt', 'featured_image', 'page_attributes', 'comments', 'discussion' ),
					'show_in_rest'   => 0,
				)
			);
		}
	}
);

// Their layout is in code, so the block editor has nothing to edit: the classic screen shows only the fields.
add_filter( 'use_block_editor_for_post', fn( $use, $post ) => get_post_meta( $post->ID, 'headless_page_key', true ) ? false : $use, 10, 2 );

// The editor explains what these pages are.
add_action(
	'edit_form_after_title',
	function ( $post ) {
		$key = get_post_meta( $post->ID, 'headless_page_key', true );
		if ( $key ) {
			printf(
				'<div class="notice notice-info inline"><p>%s</p></div>',
				esc_html( "This is the site's \"{$key}\" page. Its layout is built into the site; edit the texts, lists and images below. Empty fields show the site's default text." )
			);
		}
	}
);

add_action(
	'rest_api_init',
	function () {
		register_rest_route(
			'headless/v1',
			'/page-content/(?P<key>[a-z0-9-]+)',
			array(
				'methods'             => 'GET',
				'permission_callback' => '__return_true',
				'args'                => array( 'lang' => array( 'type' => 'string' ) ),
				'callback'            => function ( WP_REST_Request $request ) {
					$lang = sanitize_key( (string) $request['lang'] );
					$ids  = headless_page_ids( $request['key'] );
					$id   = null;
					foreach ( $ids as $candidate ) {
						if ( 'publish' === get_post_status( $candidate ) && ( ! $lang || headless_post_lang( $candidate ) === $lang ) ) {
							$id = $candidate;
						}
					}
					if ( ! $id || ! function_exists( 'get_fields' ) ) {
						return new WP_Error( 'not_found', 'No page for this key.', array( 'status' => 404 ) );
					}
					return array( 'id' => $id, 'modified' => get_post_modified_time( 'c', true, $id ), 'values' => get_fields( $id ) );
				},
			)
		);
	}
);

// "View page" in wp-admin opens the page on the site.
add_filter(
	'page_link',
	function ( $link, $id ) {
		$key = get_post_meta( $id, 'headless_page_key', true );
		$page = $key ? ( headless_site_config()['pages'][ $key ] ?? null ) : null;
		return $page ? headless_site_url( '/' . headless_post_lang( $id ) . rtrim( $page['path'], '/' ) ) : $link;
	},
	10,
	2
);

// WordPress's front end isn't the site: visitors on a content URL go to the same page there.
// Only GET requests for content without a query string, so payment steps and plugin
// endpoints on WordPress keep working.
add_action(
	'template_redirect',
	function () {
		if ( 'GET' !== ( $_SERVER['REQUEST_METHOD'] ?? '' ) || ! empty( $_SERVER['QUERY_STRING'] ) || is_preview() || is_feed() || is_robots() || is_favicon() ) {
			return;
		}
		if ( function_exists( 'is_checkout' ) && ( is_checkout() || is_cart() || is_account_page() ) ) {
			return;
		}
		$config = headless_site_config();
		$object = get_queried_object();
		$target = null;

		if ( is_singular() && $object instanceof WP_Post ) {
			$lang = headless_post_lang( $object->ID );
			$key  = get_post_meta( $object->ID, 'headless_page_key', true );
			if ( $key && isset( $config['pages'][ $key ] ) ) {
				$target = "/{$lang}" . rtrim( $config['pages'][ $key ]['path'], '/' );
			} elseif ( 'product' === $object->post_type ) {
				$target = "/{$lang}/{$config['shopPath']}/{$object->post_name}";
			}
		} elseif ( function_exists( 'is_product_category' ) && is_product_category() && $object instanceof WP_Term ) {
			$target = '/' . $config['defaultLang'] . "/{$config['shopPath']}/collections/{$object->slug}";
		} elseif ( function_exists( 'is_shop' ) && is_shop() ) {
			$target = '/' . $config['defaultLang'] . "/{$config['shopPath']}";
		}

		if ( ! $target && ( is_front_page() || is_home() || is_singular() || is_category() || is_tag() || is_404() ) ) {
			// Permalinks mirror the site's paths; the site always prefixes the language.
			$home_path = (string) wp_parse_url( home_url( '/' ), PHP_URL_PATH );
			$path      = trim( substr( (string) wp_parse_url( $_SERVER['REQUEST_URI'], PHP_URL_PATH ), strlen( $home_path ) ), '/' );
			$segments  = $path === '' ? array() : explode( '/', $path );
			$languages = function_exists( 'pll_languages_list' ) ? pll_languages_list() : array();
			if ( ! $segments || ! in_array( $segments[0], $languages, true ) ) {
				array_unshift( $segments, $config['defaultLang'] );
			}
			$target = '/' . implode( '/', $segments );
		}

		if ( $target ) {
			wp_redirect( headless_site_url( $target ), 302, 'Headless bridge' ); // phpcs:ignore WordPress.Security.SafeRedirect -- the site's own host.
			exit;
		}
	},
	5
);

/* ---------------------------------------------------------------- languages (Polylang) */

// Pages that exist for WordPress itself (WooCommerce's cart, checkout, account and shop
// pages, the posts page) aren't content: the site doesn't render them or list them.
add_action(
	'rest_api_init',
	function () {
		register_rest_field(
			'page',
			'headless_hidden',
			array(
				'get_callback' => function ( $page ) {
					if ( get_post_meta( $page['id'], 'headless_page_key', true ) ) {
						return true; // the site's own pages: built in code, only their fields are content
					}
					$system = array( (int) get_option( 'page_for_posts' ) );
					if ( function_exists( 'wc_get_page_id' ) ) {
						foreach ( array( 'cart', 'checkout', 'myaccount', 'shop' ) as $name ) {
							$system[] = (int) wc_get_page_id( $name );
						}
					}
					return in_array( (int) $page['id'], $system, true );
				},
				'schema'       => array( 'type' => 'boolean', 'context' => array( 'view', 'embed' ) ),
			)
		);
	}
);

add_action(
	'rest_api_init',
	function () {
		if ( ! function_exists( 'pll_get_post_language' ) ) {
			return;
		}

		$post_types = array_values( get_post_types( array( 'show_in_rest' => true, 'public' => true ) ) );

		register_rest_field(
			$post_types,
			'lang',
			array(
				'get_callback' => fn( $post ) => pll_get_post_language( $post['id'], 'slug' ),
				'schema'       => array( 'type' => 'string', 'context' => array( 'view', 'embed' ) ),
			)
		);

		// { "el": { "id": 12, "slug": "...", "link": "..." }, "en": { ... } }
		register_rest_field(
			$post_types,
			'translations',
			array(
				'get_callback' => function ( $post ) {
					$result = array();
					foreach ( pll_get_post_translations( $post['id'] ) as $lang => $id ) {
						if ( 'publish' === get_post_status( $id ) ) {
							$result[ $lang ] = array( 'id' => $id, 'slug' => get_post_field( 'post_name', $id ), 'link' => get_permalink( $id ) );
						}
					}
					return (object) $result;
				},
				'schema'       => array( 'type' => 'object', 'context' => array( 'view', 'embed' ) ),
			)
		);

		register_rest_field(
			array( 'category', 'post_tag' ),
			'lang',
			array( 'get_callback' => fn( $term ) => pll_get_term_language( $term['id'], 'slug' ) )
		);

		// ?lang=el on post, page and term collections (Polylang Pro has this; the free version doesn't).
		foreach ( $post_types as $type ) {
			add_filter(
				"rest_{$type}_query",
				function ( $args, $request ) {
					if ( $request['lang'] ) {
						$args['lang'] = sanitize_key( $request['lang'] );
					}
					return $args;
				},
				10,
				2
			);
		}
		foreach ( array( 'category', 'post_tag' ) as $taxonomy ) {
			add_filter(
				"rest_{$taxonomy}_query",
				function ( $args, $request ) {
					if ( $request['lang'] ) {
						$args['lang'] = sanitize_key( $request['lang'] );
					}
					return $args;
				},
				10,
				2
			);
		}
	}
);

/* ---------------------------------------------------------------- change notifications */

$headless_changes = array();

function headless_queue_change( $type, $id = 0 ) {
	global $headless_changes;
	$headless_changes[ "{$type}:{$id}" ] = array( 'type' => $type, 'id' => (int) $id );
}

// Published content changed, or left the published state.
add_action(
	'transition_post_status',
	function ( $new_status, $old_status, $post ) {
		if ( ( 'publish' === $new_status || 'publish' === $old_status ) && ! wp_is_post_revision( $post ) && is_post_type_viewable( $post->post_type ) ) {
			headless_queue_change( $post->post_type, $post->ID );
		}
	},
	10,
	3
);
add_action(
	'post_updated',
	function ( $id, $after ) {
		if ( 'publish' === $after->post_status && ! wp_is_post_revision( $id ) ) {
			headless_queue_change( $after->post_type, $id );
		}
	},
	10,
	2
);
add_action( 'deleted_post', fn( $id ) => headless_queue_change( 'post', $id ) );
// Field values (the site's own pages) can change without the post itself changing.
add_action( 'acf/save_post', fn( $id ) => is_numeric( $id ) ? headless_queue_change( get_post_type( (int) $id ), (int) $id ) : null, 20 );
foreach ( array( 'created_term', 'edited_term', 'delete_term' ) as $headless_hook ) {
	add_action( $headless_hook, fn( $term_id, $tt_id = 0, $taxonomy = '' ) => headless_queue_change( "term:{$taxonomy}", $term_id ), 10, 3 );
}
// Stock and price changes don't always touch the post.
foreach ( array( 'woocommerce_product_set_stock', 'woocommerce_variation_set_stock', 'woocommerce_product_set_stock_status' ) as $headless_hook ) {
	add_action( $headless_hook, fn( $product ) => headless_queue_change( 'product', is_object( $product ) ? $product->get_id() : $product ) );
}
add_action( 'wp_update_nav_menu', fn( $menu_id ) => headless_queue_change( 'menu', $menu_id ) );

// One signed, non-blocking request per WordPress request, however many things changed.
add_action(
	'shutdown',
	function () {
		global $headless_changes;
		if ( ! $headless_changes || ! defined( 'HEADLESS_WEBHOOK_SECRET' ) || ! HEADLESS_WEBHOOK_SECRET ) {
			return;
		}
		$body = wp_json_encode( array( 'changes' => array_values( $headless_changes ), 'site' => home_url() ) );
		wp_remote_post(
			defined( 'HEADLESS_WEBHOOK_URL' ) ? HEADLESS_WEBHOOK_URL : headless_site_url( '/api/wordpress/webhook' ),
			array(
				// WP-CLI exits right after, which would drop a non-blocking request.
				'blocking' => defined( 'WP_CLI' ) && WP_CLI,
				'timeout'  => 3,
				'headers'  => array(
					'Content-Type'         => 'application/json',
					'X-Headless-Signature' => base64_encode( hash_hmac( 'sha256', $body, HEADLESS_WEBHOOK_SECRET, true ) ),
				),
				'body'     => $body,
			)
		);
	}
);

/* ---------------------------------------------------------------- shop (WooCommerce) */

add_action(
	'plugins_loaded',
	function () {
		if ( ! class_exists( 'WooCommerce' ) ) {
			return;
		}

		// Every gateway returns the shopper to the "order received" URL after paying.
		add_filter(
			'woocommerce_get_checkout_order_received_url',
			fn( $url, $order ) => headless_site_url( '/commerce/return', array( 'order' => $order->get_id(), 'key' => $order->get_order_key() ) ),
			10,
			2
		);

		// Shoppers only reach WordPress's cart or checkout when a payment failed or was cancelled
		// (gateways send them "back to checkout", or to the "pay for order" form). The order-pay
		// step that forwards to the gateway (no pay_for_order) stays on WordPress.
		add_action(
			'template_redirect',
			function () {
				if ( is_wc_endpoint_url( 'order-received' ) ) {
					return;
				}
				if ( is_wc_endpoint_url( 'order-pay' ) ) {
					$order_id = absint( get_query_var( 'order-pay' ) );
					// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- read-only routing.
					if ( isset( $_GET['pay_for_order'] ) ) {
						wc_clear_notices();
						wp_safe_redirect( headless_site_url( '/commerce/return', array( 'payment' => 'failed', 'order' => $order_id ) ) );
						exit;
					}
					// Some gateways (e.g. Piraeus ePay) print an error on this page when they can't start
					// the payment. Headers are already sent by then, so send the shopper back from the page.
					$order = wc_get_order( $order_id );
					if ( $order ) {
						add_action(
							'woocommerce_receipt_' . $order->get_payment_method(),
							function ( $receipt_order_id ) {
								$receipt_order = wc_get_order( $receipt_order_id );
								if ( $receipt_order && $receipt_order->has_status( array( 'failed', 'cancelled' ) ) ) {
									$url = headless_site_url( '/commerce/return', array( 'payment' => 'failed', 'order' => $receipt_order->get_id() ) );
									echo '<meta http-equiv="refresh" content="0;url=' . esc_url( $url ) . '">';
								}
							},
							999
						);
					}
					return;
				}
				if ( is_checkout() || is_cart() ) {
					wc_clear_notices();
					wp_safe_redirect( headless_site_url( '/commerce/return', array( 'payment' => 'failed' ) ) );
					exit;
				}
			},
			1
		);
	}
);
